"use client";

import { useEffect, useRef, useState, useSyncExternalStore } from "react";
import Link from "next/link";
import { useSearchParams } from "next/navigation";
import { useUi } from "@/components/shell/ui-provider";
import { Icon } from "@/components/ui/icon";
import { enterDrawer } from "@/lib/drawer-focus";
import { explainStatusText, type ExplainState } from "@/lib/explain-session";
import {
  explainParam,
  getExplainSession,
  withExplainParam,
  type ExplainFactsView,
  type ExplainView,
} from "@/lib/explain-store";
import { milliseconds, numberText, percent } from "@/lib/result-presentation";

const VERDICT_TEXT = { pass: "Passes its targets", strained: "Strained", fail: "Breaks under this load" } as const;
const EVIDENCE_LABEL: Record<string, string> = {
  verdict: "Verdict",
  p95: "p95 latency",
  errorRate: "Error rate",
  bottleneck: "Bottleneck",
  noBottleneck: "No bottleneck identified",
};

/** Button beside the recorded Results. Opens the existing assistant drawer in result-explanation mode. */
export function ExplainTrigger({ view }: { view: ExplainView }) {
  const { setUI } = useUi();
  return (
    <div className="row m12-trigger">
      <button className="btn" onClick={() => setUI({ ai: true, help: false })}>
        <Icon n="sparkle" /> Explain this result
      </button>
      <span className="small muted">
        Local, experimental AI. It explains saved revision {view.runRevision} only.
        {view.unsavedChanges && " Your unsaved edits are not included."}
      </span>
    </div>
  );
}

function Facts({ facts, source }: { facts: ExplainFactsView; source: string }) {
  const p95Bad = facts.p95Ms > facts.p95TargetMs,
    errBad = facts.errorRateFraction > facts.errorBudgetFraction;
  return (
    <section className="m12-facts" aria-label="Verified facts">
      <div className="row tight m12-h">
        <h3 className="h3">Verified facts</h3>
        <span className="tag">{source}</span>
      </div>
      <dl className="m12-dl">
        <div>
          <dt>Verdict</dt>
          <dd className={facts.verdict === "pass" ? "c-ok" : facts.verdict === "strained" ? "c-warn" : "c-fail"}>
            {VERDICT_TEXT[facts.verdict]}
          </dd>
        </div>
        <div>
          <dt>p95 latency · target {milliseconds(facts.p95TargetMs)}</dt>
          <dd className={p95Bad ? "c-fail" : "c-ok"}>{milliseconds(facts.p95Ms)}</dd>
        </div>
        <div>
          <dt>Error rate · budget {percent(facts.errorBudgetFraction)}</dt>
          <dd className={errBad ? "c-fail" : "c-ok"}>{percent(facts.errorRateFraction)}</dd>
        </div>
        <div>
          <dt>Bottleneck</dt>
          <dd>
            {facts.bottleneck
              ? `${facts.bottleneck.label} · ${numberText(facts.bottleneck.utilizationFraction * 100, 0)}% utilization`
              : "None identified"}
          </dd>
        </div>
      </dl>
    </section>
  );
}

function elapsed(createdAt: string, now: number) {
  const s = Math.max(0, Math.round((now - Date.parse(createdAt)) / 1000));
  return s < 60 ? `${s} s` : `${Math.floor(s / 60)} min ${s % 60} s`;
}

function Interpretation({ state }: { state: ExplainState }) {
  const job = state.job,
    ev = state.evidence;
  if (!job?.result) return null;
  if (state.evidenceFailed)
    return (
      <div className="note warn" role="status">
        <Icon n="info" />
        <div>
          The answer finished, but its verified facts could not be loaded, so it is not shown. Retry to load them.
        </div>
      </div>
    );
  if (!ev)
    return (
      <p className="small muted" role="status">
        Loading verified facts…
      </p>
    );
  return (
    <section className="m12-ai" aria-label="AI interpretation">
      <div className="row tight m12-h">
        <h3 className="h3">AI interpretation</h3>
        <span className="tag mock" title="Generated by a small local model. It can be wrong.">
          Experimental · generated locally
        </span>
      </div>
      {!ev.structured && (
        <p className="small muted">
          Earlier experimental summary. It predates verified facts, so its wording was not checked against the numbers.
        </p>
      )}
      <p className="m12-summary">{job.result.summary}</p>
      {ev.statements.length > 0 && (
        <div className="small">
          <div className="muted">Statements checked against the verified facts (wording written by the server)</div>
          <ul className="m12-statements">
            {ev.statements.map((s) => (
              <li key={s}>{s}</li>
            ))}
          </ul>
        </div>
      )}
      <div className="small">
        <span className="muted">Evidence cited: </span>
        <ul className="m12-refs">
          {job.result.evidenceIds.map((id) => (
            <li key={id} className="chip">
              {EVIDENCE_LABEL[id] ?? id}
            </li>
          ))}
        </ul>
      </div>
      {ev.limitations.length > 0 && (
        <div className="small">
          <div className="muted">Assumptions and limitations</div>
          <ul className="m12-limits">
            {ev.limitations.map((l) => (
              <li key={l}>{l}</li>
            ))}
          </ul>
        </div>
      )}
      <details className="small">
        <summary>Provenance</summary>
        <dl className="m12-prov">
          <dt>Model</dt>
          <dd>
            {job.model} · {job.modelDigest.slice(0, 12)}
          </dd>
          <dt>Design revision · run</dt>
          <dd>
            {job.designRevision} · {job.runId.slice(0, 8)}
          </dd>
          <dt>Prompt · schema</dt>
          <dd>
            {job.promptVersion} · {job.schemaVersion}
          </dd>
          <dt>Created</dt>
          <dd>{new Date(job.createdAt).toLocaleString()}</dd>
        </dl>
      </details>
    </section>
  );
}

/** Assistant drawer in result-explanation mode. Failures stay inside it; Results and editing are untouched. */
export function ExplainDrawer({ view }: { view: ExplainView }) {
  const { setUI } = useUi();
  const session = getExplainSession();
  const state = useSyncExternalStore(session.subscribe, session.getSnapshot, session.getSnapshot);
  const search = useSearchParams();
  const heading = useRef<HTMLHeadingElement>(null);
  const [now, setNow] = useState(() => Date.now());

  // Bind to the saved result on screen, then become the visible consumer (polling starts/resumes).
  useEffect(() => {
    session.bind(view);
  }, [session, view.userId, view.designId, view.runId, view.runRevision, view.savedRevision]); // eslint-disable-line react-hooks/exhaustive-deps
  useEffect(() => {
    session.setJobListener((id) => {
      const next = withExplainParam(window.location.search, id);
      if (next !== window.location.search) window.history.replaceState(null, "", window.location.pathname + next + window.location.hash);
    });
    session.attach();
    const restoreFocus = enterDrawer(heading.current);
    return () => {
      session.detach();
      session.setJobListener(null);
      restoreFocus();
    };
  }, [session]);
  // Reload recovery: an owned job id in the URL for this exact result.
  const wanted = explainParam(search);
  useEffect(() => {
    if (wanted && session.state.phase === "idle" && !session.state.job) void session.resume(wanted);
  }, [session, wanted, view.runId, view.designId]);
  const pending = state.phase === "pending";
  useEffect(() => {
    if (!pending) return;
    const t = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(t);
  }, [pending]);

  const historical = session.historical;
  const readinessKnown = state.readiness !== null;
  const unavailable = readinessKnown && !state.readiness!.ready;
  const busyPhase = state.phase === "submitting" || pending;
  const canGenerate = !historical && !busyPhase && !state.providerStopping && !(unavailable && state.phase === "idle");
  const status = explainStatusText(state);
  const facts: ExplainFactsView | null = state.evidence?.facts
    ? {
        ...state.evidence.facts,
        bottleneck: state.evidence.facts.bottleneck
          ? { label: state.evidence.facts.bottleneck.label, utilizationFraction: state.evidence.facts.bottleneck.utilizationFraction }
          : null,
      }
    : view.facts;
  const done = state.phase === "completed";
  const generateLabel =
    state.phase === "uncertain" ? "Check the same request" : done || state.phase === "ended" || state.phase === "error" ? "Explain again" : "Explain this result";

  return (
    <aside className="drawer m12-drawer" aria-label="Result explanation" aria-busy={busyPhase}>
      <div className="drawer-h">
        <Icon n="sparkle" />
        <div className="grow">
          <h2 className="m12-title" tabIndex={-1} ref={heading}>
            Result explanation
          </h2>
          <div className="muted small">
            {view.designName} · saved revision {view.runRevision} · run {view.runId.slice(0, 8)}
            {state.job && <> · {state.job.model}</>}
          </div>
        </div>
        <span className="tag mock" title="Local model, experimental. Nothing leaves this computer.">
          Experimental
        </span>
        <button className="btn btn-ghost icon btn-sm" aria-label="Close assistant" onClick={() => setUI({ ai: false })}>
          <Icon n="x" />
        </button>
      </div>
      <div className="drawer-b stack">
        {historical && (
          <div className="note warn" role="status">
            <Icon n="info" />
            <div>
              Earlier revision. This result is for revision {view.runRevision}; the design is now at revision {view.savedRevision}. It is not
              explained as the current design. <Link href={`/designs/${view.designId}/edit`}>Run the current saved inputs</Link> to explain them.
            </div>
          </div>
        )}
        {view.unsavedChanges && (
          <p className="small muted">Explains saved revision {view.savedRevision}. Your unsaved edits are kept and not included.</p>
        )}
        {facts && <Facts facts={facts} source={state.evidence?.facts ? "Server evidence for this job" : "Recorded run"} />}
        <div role="status" aria-live="polite" className="m12-status">
          {pending && state.job && (
            <p>
              Generating locally… running for {elapsed(state.job.createdAt, now)}.{" "}
              <span className="muted">There is no progress estimate; small local models can take a while.</span>
            </p>
          )}
          {state.phase === "submitting" && <p>Sending the request…</p>}
          {state.connectionLost && <p className="c-warn small">Connection lost; the explanation may still be running. Checking again.</p>}
          {state.providerStopping && (
            <p className="small">Cancelled. The local model is still stopping, so a new explanation is unavailable for a moment.</p>
          )}
          {status && (state.phase !== "idle" || state.readiness?.reason !== "AVAILABLE") && <p>{status}</p>}
        </div>
        <Interpretation state={state} />
      </div>
      <div className="drawer-f stack">
        <div className="row tight">
          {pending ? (
            <button className="btn" onClick={() => void session.cancel()}>
              Cancel explanation
            </button>
          ) : (
            <button className="btn btn-primary" disabled={!canGenerate} onClick={() => void session.generate()}>
              {generateLabel}
            </button>
          )}
          {state.evidenceFailed && (
            <button className="btn" onClick={() => void session.loadEvidence()}>
              Retry loading facts
            </button>
          )}
          {state.phase === "idle" && (unavailable || state.readinessError) && (
            <button className="btn" onClick={() => void session.checkReadiness()}>
              Check again
            </button>
          )}
        </div>
        <div className="small muted">
          Local experimental AI. Closing this panel does not stop an accepted request; use Cancel. It never changes your design.
        </div>
      </div>
    </aside>
  );
}
