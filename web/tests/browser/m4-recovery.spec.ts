import { test, expect } from "@playwright/test";
const api=process.env.SF_API_URL??"http://localhost:5001/v1";
test("M4 empty blank, recoverable preparation errors, changed drafts and escaped labels",async({page},info)=>{
 await page.goto("/register");await page.getByLabel("Name",{exact:true}).fill("M4 Recovery");
 await page.getByLabel("Email",{exact:true}).fill("m4-recovery-"+Date.now()+"-"+info.project.name+"@example.test");
 await page.getByLabel("Password",{exact:true}).fill("M4-Recovery-2026!");await page.locator("#reg-terms").check();
 await page.getByRole("button",{name:"Create account",exact:true}).click();await expect(page.getByRole("button",{name:"Account menu",exact:true})).toBeVisible();
 await page.goto("/new/blank");await page.getByLabel("Start with",{exact:true}).selectOption("empty");await page.getByRole("button",{name:"Create blank design",exact:true}).click();
 await expect(page).toHaveURL(/\/designs\/[^/]+\/edit$/);await expect(page.getByRole("button",{name:"Run test",exact:true})).toBeVisible();
 await page.goto("/new/describe");
 await page.getByLabel("Your system, in your own words",{exact:true}).fill("3 app servers, Postgres, Redis and 500 rps");
 await page.route(api+"/designs/prepare",route=>route.fulfill({status:429,json:{error:{code:"RATE_LIMITED",message:"Temporary preparation limit"}}}));
 await page.getByRole("button",{name:"Draft the design",exact:true}).click();
 await expect(page.locator("main [role=alert]")).toContainText("Temporary preparation limit");
 await expect(page.getByLabel("Your system, in your own words",{exact:true})).toHaveValue("3 app servers, Postgres, Redis and 500 rps");
 await page.unroute(api+"/designs/prepare");
 await page.getByRole("button",{name:"Draft the design",exact:true}).click();await expect(page.getByRole("heading",{name:"Review your draft"})).toBeVisible();
 await page.getByLabel("Your system, in your own words",{exact:true}).fill("2 app servers");
 await expect(page.getByRole("button",{name:"Open in the editor",exact:true})).toHaveCount(0);
 await page.route(api+"/designs/prepare",route=>route.abort("connectionreset"));
 await page.getByRole("button",{name:"Draft the design",exact:true}).click();
 await expect(page.locator(".sys-title")).toBeVisible();
 await page.unroute(api+"/designs/prepare");
 await expect(page.getByLabel("Your system, in your own words",{exact:true})).toHaveValue("2 app servers",{timeout:20000});
 await page.goto("/new/import");
 await page.getByLabel("Design JSON",{exact:true}).fill(JSON.stringify({name:"Escaped",nodes:[{id:"a",type:"app",label:"<img src=x onerror=alert(1)>"}]}));
 await page.getByRole("button",{name:"Check import",exact:true}).click();
 await expect(page.getByRole("heading",{name:"Ready to import"})).toBeVisible();
 expect(await page.locator("main img").count()).toBe(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
