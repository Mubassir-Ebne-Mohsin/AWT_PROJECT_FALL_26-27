import { test, expect } from "@playwright/test";
test("M3 template → replicas → save → run → refresh → reopen", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
  await page.goto("/register");
  await page.getByLabel("Name", { exact: true }).fill("M3 Browser");
  await page.getByLabel("Email", { exact: true }).fill(`m3-${Date.now()}-${info.project.name}@example.test`);
  await page.getByLabel("Password", { exact: true }).fill("M3-Browser-2026!");
  await page.locator("#reg-terms").check();
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("button", { name: "Account menu", exact: true })).toBeVisible();
  await page.goto("/dashboard");
  await page.getByRole("link", { name: "New design from template" }).click();
  await page.getByRole("button", { name: "Use Single-server MVP", exact: true }).click();
  await expect(page.getByLabel("Replicas (1–200)")).toBeVisible();
  const designPath = new URL(page.url()).pathname;
  await page.getByLabel("Replicas (1–200)").fill("3");
  await expect(page.getByRole("status").filter({ hasText: /^Saved/ })).toBeVisible();
  await page.getByRole("button", { name: "Run test", exact: true }).click();
  await expect(page).toHaveURL(/\/results\?run=/);
  await expect(page.getByRole("heading", { name: "Model results" })).toBeVisible();
  await expect(page.getByText("p95 latency", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Model results" })).toBeVisible();
  await page.getByRole("link", { name: "Edit", exact: true }).click();
  await expect(page.getByLabel("Replicas (1–200)")).toHaveValue("3");
  await page.getByLabel("Replicas (1–200)").fill("4");
  await expect(page.getByText(/Stale result/)).toBeVisible();
  await expect(page.getByRole("status").filter({ hasText: /^Saved/ })).toBeVisible();
  await page.goto("/dashboard");
  await page.getByRole("link").filter({ has: page.getByRole("heading", { name: "Single-server MVP" }) }).click();
  await expect(page).toHaveURL(new RegExp(designPath+"\\?run="));
  await expect(page.getByLabel("Replicas (1–200)")).toHaveValue("4");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: `../docs/audit/m3-${info.project.name}.png` });
  await page.getByRole("button", { name: "Account menu", exact: true }).click();
  await page.getByRole("menuitem", { name: "Log out", exact: true }).click();
  await expect(page.getByRole("button", { name: "Account menu", exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
});

test("M3 retains drafts through save failure/conflict and recovers lost run acceptance", async ({ page }, info) => {
  await page.goto("/register");
  await page.getByLabel("Name", {exact:true}).fill("M3 Recovery");
  await page.getByLabel("Email", {exact:true}).fill(`m3-recovery-${Date.now()}-${info.project.name}@example.test`);
  await page.getByLabel("Password", {exact:true}).fill("M3-Recovery-2026!");
  await page.locator("#reg-terms").check();
  const registered = page.waitForResponse(r => r.url().endsWith("/auth/register") && r.status()===201);
  await page.getByRole("button",{name:"Create account",exact:true}).click();
  const token = (await (await registered).json()).data.accessToken;
  await expect(page.getByRole("button",{name:"Account menu",exact:true})).toBeVisible();
  await page.goto("/new/template");
  await page.getByRole("button",{name:"Use Single-server MVP",exact:true}).click();
  await expect(page.getByLabel("Replicas (1–200)")).toBeVisible();
  const id = new URL(page.url()).pathname.split("/")[2];
  const api = process.env.SF_API_URL ?? "http://localhost:5001/v1";
  const patchUrl = api+"/designs/"+id;
  await page.route(patchUrl, async route => {
    if(route.request().method()==="PATCH") await route.fulfill({status:503,json:{error:{code:"UNAVAILABLE",message:"Temporary test save outage"}}});
    else await route.continue();
  });
  await page.getByLabel("Replicas (1–200)").fill("5");
  await expect(page.getByRole("alert").filter({hasText:"Temporary test save outage"})).toContainText("Temporary test save outage");
  await expect(page.getByLabel("Replicas (1–200)")).toHaveValue("5");
  page.once("dialog",dialog=>dialog.dismiss());
  await page.getByRole("navigation",{name:"Breadcrumb",exact:true}).getByRole("link",{name:"Dashboard",exact:true}).click();
  await expect(page).toHaveURL(new RegExp("/designs/"+id+"/edit"));
  await page.unroute(patchUrl);
  await page.getByRole("button",{name:"Save",exact:true}).click();
  await expect(page.getByRole("status").filter({hasText:/^Saved/})).toBeVisible();
  const competing = await page.request.patch(patchUrl,{headers:{Authorization:"Bearer "+token},data:{expectedRevision:2,name:"Concurrent saved version"}});
  expect(competing.status()).toBe(200);
  await page.getByLabel("Replicas (1–200)").fill("6");
  await expect(page.getByRole("status").filter({hasText:"Save conflict"})).toBeVisible();
  await expect(page.getByLabel("Replicas (1–200)")).toHaveValue("6");
  await page.getByRole("button",{name:"Inspect current saved version"}).click();
  await expect(page.getByRole("heading",{name:"Saved revision 3: Concurrent saved version"})).toBeVisible();
  page.once("dialog",dialog=>dialog.accept());
  await page.getByRole("button",{name:"Reapply my draft deliberately"}).click();
  await expect(page.getByRole("status").filter({hasText:/^Saved/})).toBeVisible();
  let lost=false;
  await page.route(api+"/designs/"+id+"/simulate",async route=>{
    if(!lost){lost=true;await route.fetch();await route.abort("connectionreset");}
    else await route.continue();
  });
  await page.getByRole("button",{name:"Run test",exact:true}).click();
  await expect(page.getByRole("button",{name:"Retry same request"})).toBeVisible({timeout:20000});
  await page.getByRole("button",{name:"Retry same request"}).click();
  await expect(page.getByRole("heading",{name:"Model results"})).toBeVisible();
  const dashboard = await page.request.get(api+"/dashboard",{headers:{Authorization:"Bearer "+token}});
  expect(dashboard.status()).toBe(200);
  expect((await dashboard.json()).data.counts.retainedRuns).toBe(1);
  await expect(page.getByText(/Stale result/)).toHaveCount(0);
});
