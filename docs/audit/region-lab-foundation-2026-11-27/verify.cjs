/* Offline analytical evidence only; no application bootstrap, environment file or provider. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const { createHash } = require('node:crypto');
const repo = path.resolve(__dirname, '../../..');
const backend = path.join(repo, 'nest-boilerplate/nest-boilerplate');
const backendRequire = createRequire(path.join(backend, 'package.json'));
backendRequire('ts-node').register({ project: path.join(backend, 'tsconfig.json'), transpileOnly: true });
backendRequire('tsconfig-paths').register({ baseUrl: backend, paths: { '@/*': ['src/*'] } });
const directory = path.join(backend, 'src/modules/region-lab/engine');
const { simulateFoundation } = require(path.join(directory, 'engine.ts'));
const { fixture, horizon } = require(path.join(directory, 'foundation.fixture.ts'));
const deterministic = fixture();
const baseline = simulateFoundation(deterministic);
assert.deepEqual(simulateFoundation(deterministic), baseline);
const overload = fixture();
overload.workload.baselineRps = 100;
overload.nodes[0].serviceTime = { kind: 'constant', valueMs: 20 };
const queued = simulateFoundation(overload);
assert.equal(queued.summary.latency.meanMs, 515);
const analytical = [1, 42, 999].map(seed => {
  const input = horizon(fixture(), 300000);
  Object.assign(input.workload, { arrival: 'poisson', baselineRps: 50, warmupMs: 30000, drainMs: 60000 });
  input.seed = seed;
  input.workload.operations[0].deadlineMs = 60000;
  Object.assign(input.nodes[0], { waitingCapacityPerReplica: 10000, serviceTime: { kind: 'exponential', meanMs: 10 } });
  const r = simulateFoundation(input);
  const expectedP95Ms = -Math.log(0.05) / 50 * 1000;
  assert.ok(r.summary.latency.meanMs > 18 && r.summary.latency.meanMs < 22);
  assert.ok(Math.abs(r.summary.latency.p95Ms - expectedP95Ms) / expectedP95Ms < 0.15);
  assert.ok(r.nodes[0].utilizationRatio > 0.47 && r.nodes[0].utilizationRatio < 0.53);
  assert.equal(r.summary.failedRequests, 0);
  assert.equal(r.summary.unresolvedRequests, 0);
  return { seed, input, summary: r.summary, utilizationRatio: r.nodes[0].utilizationRatio, diagnostics: r.diagnostics, inputHash: r.inputHash, expected: { meanMs: 20, p95Ms: expectedP95Ms, utilizationRatio: 0.5 } };
});
const hashes = Object.fromEntries(fs.readdirSync(directory).filter(n => n.endsWith('.ts')).sort().map(n => [n, createHash('sha256').update(fs.readFileSync(path.join(directory, n))).digest('hex')]));
const evidence = { date: '2026-11-27', stage: 'uncalibrated-foundation', nodeVersion: process.version, scope: 'Offline kernel and analytical checks; not measured hardware, regional simulation, or production calibration', deterministicReplay: true, sourceSha256: hashes, deterministicInput: deterministic, deterministicResult: baseline, overloadedInput: overload, overloadedResult: queued, analytical };
fs.writeFileSync(path.join(__dirname, 'verification.json'), JSON.stringify(evidence, null, 2) + '\n');
console.log(JSON.stringify({ deterministicReplay: true, analytical: analytical.map(r => ({ seed: r.seed, requests: r.summary.offeredRequests, meanMs: r.summary.latency.meanMs, p95Ms: r.summary.latency.p95Ms, utilizationRatio: r.utilizationRatio })) }, null, 2));
