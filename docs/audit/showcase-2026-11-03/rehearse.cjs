// Disposable, same-account showcase rehearsal. Never writes credentials, bearer/share tokens or response bodies to evidence.
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../../..');
const { chromium, expect } = require(path.join(root, 'web/node_modules/@playwright/test'));
const web = 'http://localhost:3003', api = 'http://localhost:5003/v1';
const evidence = { scope: 'one disposable owner account; real UI and real local API; no inference', steps: [], consoleErrors: [] };
let browser;
function safe(message) { return String(message).replace(/\/share\/[A-Za-z0-9_-]{43}/g, '/share/[redacted]').replace(/gsk_[A-Za-z0-9]+/g, '[redacted]'); }
(async () => {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ baseURL: web, viewport: { width: 1440, height: 900 }, colorScheme: 'light' });
  const page = await context.newPage();
  page.on('pageerror', e => evidence.consoleErrors.push(safe(e.message)));
  await page.goto('/register?next=%2Fdashboard');
  await page.getByLabel('Name', {exact:true}).fill('Showcase audit');
  await page.getByLabel('Email', {exact:true}).fill('showcase-'+crypto.randomUUID()+'@example.test');
  await page.getByLabel('Password', {exact:true}).fill('Showcase-'+crypto.randomUUID()+'!');
  await page.locator('#reg-terms').check();
  const registered=page.waitForResponse(r=>r.url()===api+'/auth/register' && r.status()===201);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  const token=(await (await registered).json()).data.accessToken;
  const headers={Authorization:'Bearer '+token};
  await expect(page).toHaveURL(/\/dashboard$/);
  const ready=await (await page.request.get(api+'/ai/readiness',{headers})).json();
  assert.equal(ready.data.enabled,false);
  evidence.steps.push('Register, dashboard and authenticated AI-off readiness');
  await page.goto('/new/template');
  await page.getByRole('button',{name:'Use Classic three-tier web app',exact:true}).click();
  await expect(page.getByLabel('Component',{exact:true})).toBeVisible();
  const id=new URL(page.url()).pathname.split('/')[2];
  const read=async()=>{const r=await page.request.get(api+'/designs/'+id,{headers});assert.equal(r.status(),200);return(await r.json()).data;};
  await page.getByRole('link',{name:'Traffic',exact:true}).click();
  const saved=page.waitForResponse(r=>r.url()===api+'/designs/'+id && r.request().method()==='PATCH' && r.status()===200);
  await page.getByLabel('Average requests per second',{exact:true}).fill('2000');
  await saved;
  await expect(page.getByRole('status').filter({hasText:/^Saved ·/})).toBeVisible();
  const before=await read();assert.equal(before.traffic.rps,2000);
  async function run(){
    const accepted=page.waitForResponse(r=>r.url()===api+'/designs/'+id+'/simulate' && r.status()===202);
    await page.getByRole('button',{name:'Run test',exact:true}).click();
    const run=(await(await accepted).json()).data.run;
    await expect(page).toHaveURL(new RegExp('/results\\?run='+run.id+'$'));
    await expect(page.getByRole('heading',{name:'Model results',exact:true})).toBeVisible();
    let recorded;
    await expect.poll(async()=>{const r=await page.request.get(api+'/designs/'+id+'/runs/'+run.id,{headers});assert.equal(r.status(),200);recorded=(await r.json()).data;return recorded.status;},{timeout:20000}).toBe('completed');
    return recorded;
  }
  const first=await run();assert.equal(first.result.summary.verdict,'fail');
  assert.ok(Math.abs(first.result.summary.p95-1842.07)<0.01,'Documented starting p95 drifted');
  evidence.before={revision:before.revision,...first.result.summary};
  evidence.steps.push('Create three-tier design, save 2000 rps and run: failing documented case');
  await page.getByTestId('fixes-button').click();
  const card=page.getByTestId('fix-card').filter({hasText:'Double the copies'});
  await expect(card).toBeVisible();
  await card.getByTestId('fix-apply').click();
  await expect(page.getByTestId('fix-applied')).toContainText('unsaved change');
  assert.equal((await read()).revision,before.revision);
  await page.getByRole('link',{name:'Open the editor',exact:true}).click();
  const fixSaved=page.waitForResponse(r=>r.url()===api+'/designs/'+id && r.request().method()==='PATCH' && r.status()===200);
  await page.getByRole('button',{name:'Save',exact:true}).click();
  const after=(await(await fixSaved).json()).data;
  const second=await run();
  assert.equal(second.result.summary.verdict,'strained');
  assert.ok(Math.abs(second.result.summary.p95-41.26)<0.01,'Documented fixed p95 drifted');
  assert.equal(second.result.summary.errorRate,0);
  evidence.after={revision:after.revision,...second.result.summary};
  evidence.steps.push('Apply double-copies as draft, explicitly save and rerun: strained, zero model errors');
  await page.getByRole('link',{name:/^History/}).click();
  const history=page.getByRole('region',{name:'Version history'});
  await history.getByLabel('Select revision '+before.revision+' to compare').check();
  await history.getByLabel('Select revision '+after.revision+' to compare').check();
  const comparison=page.getByRole('region',{name:'Comparison of revision '+before.revision+' and revision '+after.revision});
  await expect(comparison).toContainText('same traffic and model version');
  const compared=await(await page.request.get(api+'/designs/'+id+'/compare?a='+before.revision+'&b='+after.revision,{headers})).json();
  assert.equal(compared.data.comparable,true);assert.ok(compared.data.deltas.p95<0);
  evidence.steps.push('Compare both saved revisions: same traffic/model, lower p95');
  await page.goto('/designs/'+id+'/results?run='+second.id);
  await page.getByTestId('ladder-button').click();
  await expect(page.getByTestId('ladder-row')).toHaveCount(4);
  await expect(page.getByTestId('ladder-headline')).toContainText('Already strained');
  evidence.steps.push('Load ladder: recorded load plus 2x, 5x and 10x');
  await page.goto('/designs/'+id+'/report');
  await expect(page.getByTestId('report-verdict')).toHaveText('Strained: close to its limits');
  await page.screenshot({path:path.join(__dirname,'report-light.png')});
  await page.emulateMedia({media:'print'});
  assert.equal(await page.getByRole('article',{name:'Design report'}).isVisible(),true);
  await page.emulateMedia({media:'screen'});
  evidence.steps.push('Report shows recorded result and remains visible in print media');
  await page.goto('/designs/'+id+'/share');
  await page.getByRole('button',{name:'Create link',exact:true}).click();
  const link=await page.getByTestId('share-fresh').getByLabel('Share link').inputValue();
  assert.equal(new URL(link).origin,web);
  const guest=await browser.newContext({viewport:{width:1024,height:900},colorScheme:'dark'});
  const viewer=await guest.newPage();viewer.on('pageerror',e=>evidence.consoleErrors.push(safe(e.message)));
  await viewer.goto(link);
  await expect(viewer.getByTestId('share-banner')).toContainText('Read-only copy');
  await expect(viewer.getByTestId('report-verdict')).toHaveText('Strained: close to its limits');
  await expect(viewer.getByRole('button',{name:'Account menu',exact:true})).toHaveCount(0);
  await expect(viewer.getByRole('textbox')).toHaveCount(0);
  evidence.steps.push('Anonymous read-only share opens the frozen recorded result');
  await guest.close();
  await page.goto('/evaluation/ai');
  await expect(page.getByTestId('hosted-goal-guard')).toContainText('7/7, so the attempt was NO-GO');
  await expect(page.getByTestId('hosted-goal-guard-result')).toContainText('experimental and off by default');
  await page.getByTestId('hosted-goal-guard').screenshot({path:path.join(__dirname,'guard-evaluation-light.png')});
  for(const width of [1024,390]){await page.setViewportSize({width,height:900});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);}
  evidence.steps.push('Evaluation keeps the failed gate and demo caveat visible; 1024/390 px no overflow');
  await page.getByRole('button',{name:'Account menu',exact:true}).click();
  await page.getByRole('menuitem',{name:'Log out',exact:true}).click();
  await expect(page.getByRole('button',{name:'Account menu',exact:true})).toHaveCount(0);
  evidence.steps.push('Logout');
  assert.deepEqual(evidence.consoleErrors,[]);
  evidence.status='passed';
})().catch(e=>{evidence.status='failed';evidence.failure=safe(e.message);process.exitCode=1;}).finally(async()=>{
  await browser?.close();
  fs.writeFileSync(path.join(__dirname,'journey.json'),JSON.stringify(evidence,null,2)+'\n');
  console.log(JSON.stringify({status:evidence.status,completedSteps:evidence.steps.length,...(evidence.failure?{failure:evidence.failure}:{})}));
});
